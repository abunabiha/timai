async def seed_role_templates_if_needed(db: AsyncSession) -> None:
    """Seed or update RoleTemplate entries in the database."""
    for role_data in ROLE_DEFINITIONS:
        res = await db.execute(
            select(RoleTemplate).where(
                RoleTemplate.id == role_data["id"],
                RoleTemplate.version == role_data["version"],
            )
        )
        existing = res.scalar_one_or_none()
        if not existing:
            template = RoleTemplate(
                id=role_data["id"],
                version=role_data["version"],
                name=role_data["name"],
                competencies=role_data["competencies"],
                tier_min=role_data["tier_min"],
                tier_default=role_data["tier_default"],
                tools=role_data["tools"],
                prompt=role_data["prompt"],
                dod=role_data["dod"],
            )
            db.add(template)
    await db.commit()
